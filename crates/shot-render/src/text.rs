/// Draw `text` with its top-left at (x, y); `height` is the glyph height in
/// pixels. Supports '\n'. Returns the drawn width in pixels. Uses the
/// system-font rasterizer when a face is available; this bitmap font is
/// the no-font fallback (and what tests exercise on font-less machines).
pub fn draw_text(img: &mut RgbaImage, x: f32, y: f32, height: f32, text: &str, color: Color) -> f32 {
    if let Some(w) = crate::font::draw_text(img, x, y, height, text, color) {
        return w;
    }
    draw_text_bitmap(img, x, y, height, text, color)
}

fn draw_text_bitmap(img: &mut RgbaImage, x: f32, y: f32, height: f32, text: &str, color: Color) -> f32 {
    let scale = (height / 7.0).max(1.0);
    let block = scale.ceil() as i32;
    let advance = 6.0 * scale;
    let mut max_width = 0.0f32;
    for (line_idx, line) in text.split('\n').enumerate() {
        let ly = y + line_idx as f32 * 9.0 * scale;
        let mut cx = x;
        for ch in line.chars() {
            if let Some(rows) = glyph(ch) {
                for (row, bits) in rows.iter().enumerate() {
                    for col in 0..5 {
                        if bits & (1 << (4 - col)) != 0 {
                            let px0 = (cx + col as f32 * scale) as i32;
                            let py0 = (ly + row as f32 * scale) as i32;
                            for dy in 0..block {
                                for dx in 0..block {
                                    let (px, py) = (px0 + dx, py0 + dy);
                                    if img.in_bounds(px, py) {
                                        img.blend(px as u32, py as u32, color);
                                    }
                                }
                            }
                        }
                    }
                }
            }
            cx += advance;
        }
        max_width = max_width.max(cx - x);
    }
    max_width
}

/// Pixel width of the widest line at the given glyph height (system font
/// when available, bitmap estimate otherwise).
pub fn measure(text: &str, height: f32) -> f32 {
    if let Some(w) = crate::font::measure(text, height) {
        return w;
    }
    let scale = (height / 7.0).max(1.0);
    text.split('\n')
        .map(|l| l.len() as f32 * 6.0 * scale)
        .fold(0.0f32, f32::max)
}
