//! Prototype text rasterization: a hand-built 5x7 bitmap font (original
//! minimal glyphs — no bundled font files, nothing licensed). Covers A–Z,
//! 0–9 and common punctuation; lowercase renders as uppercase. This exists
//! so Text primitives render honestly in the prototype; the production
//! milestone swaps in real font shaping (system fonts via the dependency
//! auto-install law), keeping this as the no-font fallback.

use crate::image::RgbaImage;
use shot_model::Color;

